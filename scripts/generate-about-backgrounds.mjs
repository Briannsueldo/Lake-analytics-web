/**
 * Background art for the About section, used in both themes:
 *
 *   public/images/about-mesh.svg  a wireframe terrain mesh seen in perspective, calm on the left,
 *                                 ridges on the horizon and a swell rising into the top right.
 *
 * White strokes on transparency; the site uses it as a mask tinted with the theme's ink.
 *
 *   node scripts/generate-about-backgrounds.mjs
 */
import { writeFileSync } from 'node:fs'

const W = 1920
const H = 860
const r1 = (n) => Math.round(n * 10) / 10

// --- Noise -------------------------------------------------------------------------------------
function hash(ix, iy) {
  let h = (Math.imul(ix, 374761393) + Math.imul(iy, 668265263)) | 0
  h = Math.imul(h ^ (h >>> 13), 1274126177)
  h ^= h >>> 16
  return (h >>> 0) / 4294967296
}
function vnoise(x, y) {
  const ix = Math.floor(x)
  const iy = Math.floor(y)
  const fx = x - ix
  const fy = y - iy
  const ux = fx * fx * fx * (fx * (fx * 6 - 15) + 10)
  const uy = fy * fy * fy * (fy * (fy * 6 - 15) + 10)
  const a = hash(ix, iy)
  const b = hash(ix + 1, iy)
  const c = hash(ix, iy + 1)
  const d = hash(ix + 1, iy + 1)
  return a + (b - a) * ux + (c - a) * uy + (a - b - c + d) * ux * uy
}
function fbm(x, y, octaves = 4) {
  let sum = 0
  let amp = 0.5
  let freq = 1
  let norm = 0
  for (let i = 0; i < octaves; i++) {
    sum += amp * vnoise(x * freq + i * 17.3, y * freq - i * 9.1)
    norm += amp
    amp *= 0.5
    freq *= 2.03
  }
  return sum / norm
}
const smooth = (e0, e1, x) => {
  const t = Math.min(1, Math.max(0, (x - e0) / (e1 - e0)))
  return t * t * (3 - 2 * t)
}

const svgFile = (body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" preserveAspectRatio="xMidYMid slice">
<!-- Generated by scripts/generate-about-backgrounds.mjs -->
<g fill="none" stroke="#fff" stroke-linecap="round" stroke-linejoin="round">
${body}
</g>
</svg>
`
const pathOf = (pts) => pts.map(([x, y], i) => `${i ? 'L' : 'M'}${r1(x)} ${r1(y)}`).join('')

// --- Light: wireframe terrain mesh ---------------------------------------------------------------
function mesh() {
  const PITCH = (13 * Math.PI) / 180
  const DIST = 6
  const FOCAL = 1150
  const sinP = Math.sin(PITCH)
  const cosP = Math.cos(PITCH)
  const project = (x, y, h) => {
    const vy = y + DIST * cosP
    const vz = h - DIST * sinP
    const cy = vy * sinP + vz * cosP
    const cz = vy * cosP - vz * sinP
    return [W * 0.38 + (FOCAL * x) / cz, H * 0.6 - (FOCAL * cy) / cz, cz]
  }
  // Calm on the left, swelling into ridges towards the right and the horizon.
  const height = (x, y) => {
    const rise = smooth(-4, 10, x + y * 0.2)
    const far = smooth(3, 18, y)
    // A long swell that crests on the right and rolls towards the viewer.
    const swell = smooth(1, 14, x) * Math.exp(-((y - 5.5 + x * 0.12) ** 2) / 34)
    return (
      0.7 * rise * (fbm(x * 0.16 + 3, y * 0.16, 4) - 0.35) +
      2.4 * far * (fbm(x * 0.09, y * 0.09 + 7, 4) - 0.25) +
      4.4 * swell * (0.85 + 0.3 * fbm(x * 0.2, y * 0.2, 3)) +
      0.3 * Math.sin(x * 0.3 + y * 0.22) * rise -
      0.55
    )
  }

  const NX = 120
  const NY = 96
  const X0 = -12
  const X1 = 18
  const Y0 = -3.6
  const Y1 = 30
  const grid = []
  for (let j = 0; j < NY; j++) {
    // Rows packed closer near the viewer so cells read evenly in perspective.
    const t = j / (NY - 1)
    const y = Y0 + (Y1 - Y0) * Math.pow(t, 1.55)
    const row = []
    for (let i = 0; i < NX; i++) {
      const x = X0 + ((X1 - X0) * i) / (NX - 1)
      row.push(project(x, y, height(x, y)))
    }
    grid.push(row)
  }
  const alphaAt = (z) => Math.max(0.16, Math.min(0.7, 1.1 - z / 30))
  const lines = []
  const emit = (pts) => {
    const visible = pts.filter(([x, y]) => x > -200 && x < W + 200 && y > -200 && y < H + 200)
    if (visible.length < 2) return
    const z = visible.reduce((s, p) => s + p[2], 0) / visible.length
    lines.push(`<path d="${pathOf(visible)}" stroke-width="0.7" stroke-opacity="${alphaAt(z).toFixed(2)}"/>`)
  }
  for (const row of grid) emit(row)
  for (let i = 0; i < NX; i++) emit(grid.map((row) => row[i]))
  return svgFile(lines.join('\n'))
}

for (const [name, svg] of [
  ['public/images/about-mesh.svg', mesh()],
]) {
  writeFileSync(name, svg)
  console.log(`Wrote ${name}: ${(svg.length / 1024).toFixed(0)} KB`)
}
